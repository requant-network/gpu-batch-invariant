// ---------------------------------------------------------------------------
// COST — experiment 3a: resident latency (data on device, CUDA events around
// a single launch, no transfers). Warmup 10, reps 30 (GEMM) / 100 (row/attn).
// ---------------------------------------------------------------------------
struct LatStats { double med, mn, mx; };
template <typename F>
static LatStats time_resident(F launch, int warmup, int reps) {
  for (int i = 0; i < warmup; i++) launch();
  CUDA_CHECK(cudaDeviceSynchronize());
  std::vector<double> ts;
  cudaEvent_t e0, e1;
  CUDA_CHECK(cudaEventCreate(&e0)); CUDA_CHECK(cudaEventCreate(&e1));
  for (int i = 0; i < reps; i++) {
    CUDA_CHECK(cudaEventRecord(e0));
    launch();
    CUDA_CHECK(cudaEventRecord(e1));
    CUDA_CHECK(cudaEventSynchronize(e1));
    float ms = 0; CUDA_CHECK(cudaEventElapsedTime(&ms, e0, e1));
    ts.push_back(ms);
  }
  CUDA_CHECK(cudaEventDestroy(e0)); CUDA_CHECK(cudaEventDestroy(e1));
  std::sort(ts.begin(), ts.end());
  LatStats s;
  s.med = ts[ts.size() / 2];
  s.mn = ts.front(); s.mx = ts.back();
  return s;
}
static void lat_json(const char* kernel, const char* params, int M,
                     LatStats std_, LatStats inv, int reps) {
  double ov = (inv.med - std_.med) / std_.med * 100.0;
  printf("{\"kernel\":\"%s\",%s,\"M\":%d,\"boundary\":\"resident\",\"warmup\":10,\"reps\":%d,"
         "\"std_median_ms\":%.6f,\"std_min_ms\":%.6f,\"std_max_ms\":%.6f,"
         "\"inv_median_ms\":%.6f,\"inv_min_ms\":%.6f,\"inv_max_ms\":%.6f,"
         "\"overhead_pct\":%.3f}\n",
         kernel, params, M, reps, std_.med, std_.mn, std_.mx, inv.med, inv.mn, inv.mx, ov);
}

static void cost_gemm() {
  const int Ms[2] = {1, 128};
  for (int dti = 0; dti < 3; dti++) {
    DType dt = (DType)dti;
    for (int si = 0; si < 3; si++) {
      int K = GEMM_SHAPES[si].K, N = GEMM_SHAPES[si].N;
      Rng rng(SEEDS[0]);
      std::vector<char> hA, hB;
      fill_grid(hA, (size_t)MAXB * K, dt, rng);
      fill_grid(hB, (size_t)K * N, dt, rng);
      DevBuf dA, dB, dC;
      dA.alloc(hA.size()); dA.upload(hA.data(), hA.size());
      dB.alloc(hB.size()); dB.upload(hB.data(), hB.size());
      dC.alloc((size_t)MAXB * N * dtype_size(dt));
      for (int mi = 0; mi < 2; mi++) {
        int M = Ms[mi];
        LtGemm g; g.init(dt, M, N, K);
        LatStats s = time_resident([&]() { g.run(dA.p, dB.p, dC.p, 0); }, 10, 30);
        LatStats v;
        if (dt == FP16) v = time_resident([&]() { launch_gemm_inv<__half>((const __half*)dA.p, (const __half*)dB.p, (__half*)dC.p, M, N, K, 0); }, 10, 30);
        else if (dt == BF16) v = time_resident([&]() { launch_gemm_inv<__nv_bfloat16>((const __nv_bfloat16*)dA.p, (const __nv_bfloat16*)dB.p, (__nv_bfloat16*)dC.p, M, N, K, 0); }, 10, 30);
        else v = time_resident([&]() { launch_gemm_inv<float>((const float*)dA.p, (const float*)dB.p, (float*)dC.p, M, N, K, 0); }, 10, 30);
        char params[160];
        snprintf(params, sizeof(params), "\"dtype\":\"%s\",\"shape\":\"%s\",\"K\":%d,\"N\":%d",
                 dtype_name(dt), GEMM_SHAPES[si].name, K, N);
        lat_json("gemm", params, M, s, v, 30);
        g.destroy();
      }
      dA.free_(); dB.free_(); dC.free_();
    }
  }
}

static void cost_rows() {
  const int widths[2] = {4096, 11008};
  const int Bs[2] = {1, 128};
  for (int wi = 0; wi < 2; wi++) {
    int N = widths[wi];
    Rng rng(SEEDS[0]);
    std::vector<char> hx; fill_grid(hx, (size_t)MAXB * N, FP32, rng);
    std::vector<float> hw(N);
    if (wi == 0) for (int i = 0; i < N; i++) hw[i] = rng.weight();
    DevBuf dx, dy, dw;
    dx.alloc(hx.size()); dx.upload(hx.data(), hx.size());
    dy.alloc((size_t)MAXB * N * 4);
    if (wi == 0) { dw.alloc(N * 4); dw.upload(hw.data(), N * 4); }
    for (int bi = 0; bi < 2; bi++) {
      int B = Bs[bi];
      int T = row_block_heuristic(B);
      LatStats s = time_resident([&]() {
        softmax_kernel<float><<<B, T, (T / 32) * 4>>>((const float*)dx.p, (float*)dy.p, N);
      }, 10, 100);
      LatStats v = time_resident([&]() {
        softmax_kernel<float><<<B, ROW_BLOCK_INV, (ROW_BLOCK_INV / 32) * 4>>>((const float*)dx.p, (float*)dy.p, N);
      }, 10, 100);
      char params[96]; snprintf(params, sizeof(params), "\"N\":%d", N);
      lat_json("softmax", params, B, s, v, 100);
      if (wi == 0) {
        LatStats s2 = time_resident([&]() {
          rmsnorm_kernel<float><<<B, T, (T / 32) * 4>>>((const float*)dx.p, (const float*)dw.p, (float*)dy.p, N, 1e-5f);
        }, 10, 100);
        LatStats v2 = time_resident([&]() {
          rmsnorm_kernel<float><<<B, ROW_BLOCK_INV, (ROW_BLOCK_INV / 32) * 4>>>((const float*)dx.p, (const float*)dw.p, (float*)dy.p, N, 1e-5f);
        }, 10, 100);
        lat_json("rmsnorm", params, B, s2, v2, 100);
      }
    }
    dx.free_(); dy.free_(); dw.free_();
  }
}

