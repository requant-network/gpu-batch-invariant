// ---------------------------------------------------------------------------
// Naive tiled attention: one block per (batch, head, query). Scores computed
// with a block reduction over head_dim, softmax over S, then out[d] accumulates
// p[s]*V[s,d] in ascending s. blockDim depends on batch in the standard
// variant (changes the dot-product reduction grouping); invariant freezes 128.
// Q,K,V,O layout: [B, H, S, D] contiguous, fp16 storage, fp32 compute.
// ---------------------------------------------------------------------------
__global__ void attn_kernel(const __half* Q, const __half* K, const __half* V,
                            __half* O, int H, int S, int D) {
  extern __shared__ float sm[];
  float* scores = sm;                    // S floats
  float* red = sm + S;                   // blockDim.x/32 floats
  int q = blockIdx.x, h = blockIdx.y, b = blockIdx.z;
  size_t base = ((size_t)b * H + h) * S;
  const __half* qrow = Q + (base + q) * D;
  const __half* kbase = K + base * D;
  const __half* vbase = V + base * D;
  __half* orow = O + (base + q) * D;

  // Pass 1: scores[s] = dot(q, k_s), fixed ascending d within each thread.
  for (int s = 0; s < S; s++) {
    const __half* kr = kbase + (size_t)s * D;
    float part = 0.0f;
    for (int d = threadIdx.x; d < D; d += blockDim.x)
      part += __half2float(qrow[d]) * __half2float(kr[d]);
    float tot = block_sum(part, red);
    if (threadIdx.x == 0) scores[s] = tot;
    __syncthreads();
  }
  // Pass 2: softmax over scores (fixed two-pass order).
  float m = -INFINITY;
  for (int s = threadIdx.x; s < S; s += blockDim.x) m = fmaxf(m, scores[s]);
  m = block_max(m, red);
  float sum = 0.0f;
  for (int s = threadIdx.x; s < S; s += blockDim.x) sum += expf(scores[s] - m);
  sum = block_sum(sum, red);
  float inv = 1.0f / sum;
  for (int s = threadIdx.x; s < S; s += blockDim.x) scores[s] = expf(scores[s] - m) * inv;
  __syncthreads();
  // Pass 3: out[d] = sum_s p[s] * V[s,d], ascending s, fp32 accumulator.
  for (int d = threadIdx.x; d < D; d += blockDim.x) {
    float acc = 0.0f;
    for (int s = 0; s < S; s++)
      acc += scores[s] * __half2float(vbase[(size_t)s * D + d]);
    orow[d] = __float2half_rn(acc);
  }
}

