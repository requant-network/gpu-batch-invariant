// Exact fp64 sequential oracle for one GEMM probe row (row 0 of A).
// Returns exact outputs, sum of |a*b| (for the proven bound), all in fp64.
static void gemm_oracle_row(const std::vector<char>& hA, const std::vector<char>& hB,
                            int K, int N, DType dt, std::vector<double>& out,
                            std::vector<double>& sabs) {
  out.assign(N, 0.0); sabs.assign(N, 0.0);
  std::vector<double> a(K);
  for (int k = 0; k < K; k++) a[k] = (double)elem_to_f32(hA.data(), k, dt);
  for (int j = 0; j < N; j++) {
    double acc = 0.0, sa = 0.0;
    for (int k = 0; k < K; k++) {
      double b = (double)elem_to_f32(hB.data(), (size_t)k * N + j, dt);
      double p = a[k] * b;
      acc += p;
      sa += fabs(p);
    }
    out[j] = acc; sabs[j] = sa;
  }
}

static double gamma_bound(int K, double sabs) {
  double u = ldexp(1.0, -24);
  double g = (K * u) / (1.0 - K * u);
  return g * sabs;
}

static void invariant_gemm() {
  for (int dti = 0; dti < 3; dti++) {
    DType dt = (DType)dti;
    for (int si = 0; si < 3; si++) {
      int K = GEMM_SHAPES[si].K, N = GEMM_SHAPES[si].N;
      for (int seedi = 0; seedi < 2; seedi++) {
        uint64_t seed = SEEDS[seedi];
        Rng rng(seed);
        std::vector<char> hA, hB;
        fill_grid(hA, (size_t)MAXB * K, dt, rng);
        fill_grid(hB, (size_t)K * N, dt, rng);
        DevBuf dA, dB, dC;
        dA.alloc(hA.size()); dA.upload(hA.data(), hA.size());
        dB.alloc(hB.size()); dB.upload(hB.data(), hB.size());
        dC.alloc((size_t)MAXB * N * dtype_size(dt));
        std::vector<char> ref(N * dtype_size(dt)), cur(N * dtype_size(dt)), cub(N * dtype_size(dt));
        bool have_ref = false, pass = true;
        size_t total_diff = 0;
        double max_abs_ref = 0.0; int64_t max_ulp_ref = 0;
        double max_err_inv = 0.0, max_err_cub = 0.0, max_bound = 0.0;
        bool bound_ok = true;
        std::vector<double> ex, sa;
        for (int bi = 0; bi < 5; bi++) {
          int M = BATCHES[bi];
          if (dt == FP16) launch_gemm_inv<__half>((const __half*)dA.p, (const __half*)dB.p, (__half*)dC.p, M, N, K, 0);
          else if (dt == BF16) launch_gemm_inv<__nv_bfloat16>((const __nv_bfloat16*)dA.p, (const __nv_bfloat16*)dB.p, (__nv_bfloat16*)dC.p, M, N, K, 0);
          else launch_gemm_inv<float>((const float*)dA.p, (const float*)dB.p, (float*)dC.p, M, N, K, 0);
          CUDA_CHECK(cudaDeviceSynchronize());
          dC.download(cur.data(), (size_t)N * dtype_size(dt));
          if (!have_ref) {
            memcpy(ref.data(), cur.data(), ref.size()); have_ref = true;
            LtGemm g; g.init(dt, 1, N, K);
            g.run(dA.p, dB.p, dC.p, 0);
            CUDA_CHECK(cudaDeviceSynchronize());
            dC.download(cub.data(), cub.size());
            g.destroy();
            CmpResult cr = cmp_rows(cub.data(), ref.data(), N, dt);
            max_ulp_ref = cr.max_ulp; max_abs_ref = cr.max_abs;
            gemm_oracle_row(hA, hB, K, N, dt, ex, sa);
            for (int j = 0; j < N; j++) {
              double bd = gamma_bound(K, sa[j]);
              double ei = fabs((double)elem_to_f32(ref.data(), j, dt) - ex[j]);
              double ec = fabs((double)elem_to_f32(cub.data(), j, dt) - ex[j]);
              max_err_inv = std::max(max_err_inv, ei);
              max_err_cub = std::max(max_err_cub, ec);
              max_bound = std::max(max_bound, bd);
              if (ei > bd || ec > bd) bound_ok = false;
            }
            if (dt == FP32 && si == 0 && seedi == 0) {
              printf("{\"kernel\":\"gemm_oracle_dump\",\"dtype\":\"fp32\",\"K\":%d,\"N\":%d,\"seed\":%llu,"
                     "\"exact_row\":[", K, N, (unsigned long long)seed);
              for (int j = 0; j < N; j++) printf("%s%.17g", j ? "," : "", ex[j]);
              printf("],\"sabs_row\":[");
              for (int j = 0; j < N; j++) printf("%s%.17g", j ? "," : "", sa[j]);
              printf("],\"gpu_inv_row\":[");
              for (int j = 0; j < N; j++) printf("%s%.9g", j ? "," : "", elem_to_f32(ref.data(), j, dt));
              printf("],\"gpu_cublas_row\":[");
              for (int j = 0; j < N; j++) printf("%s%.9g", j ? "," : "", elem_to_f32(cub.data(), j, dt));
              printf("]}\n");
            }
          }
          CmpResult c = cmp_rows(ref.data(), cur.data(), N, dt);
          if (!c.identical()) pass = false;
          total_diff += c.diff;
        }
        printf("{\"kernel\":\"gemm_invariant\",\"dtype\":\"%s\",\"shape\":\"%s\",\"K\":%d,\"N\":%d,"
               "\"seed\":%llu,\"acceptance_pass\":%s,\"total_diff_elements\":%zu,"
               "\"max_ulp_vs_cublas_m1\":%lld,\"max_abs_vs_cublas_m1\":%.9g,"
               "\"oracle_max_abs_err_invariant\":%.9g,\"oracle_max_abs_err_cublas\":%.9g,"
               "\"oracle_max_bound\":%.9g,\"oracle_bound_pass\":%s}\n",
               dtype_name(dt), GEMM_SHAPES[si].name, K, N, (unsigned long long)seed,
               pass ? "true" : "false", total_diff, (long long)max_ulp_ref, max_abs_ref,
               max_err_inv, max_err_cub, max_bound, bound_ok ? "true" : "false");
        dA.free_(); dB.free_(); dC.free_();
      }
    }
  }
}

