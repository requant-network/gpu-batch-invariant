// ---------------------------------------------------------------------------
// Batch-invariant GEMM: fixed 32x32 output tile, sequential ascending-K
// accumulation in fp32, no split-K, batch padded to a multiple of the tile.
// Each output tile is computed independently of all other tiles, so the probe
// row's bits cannot depend on the batch size. Grid: (N/32, ceil(M/32)).
// ---------------------------------------------------------------------------
template <typename T>
__global__ void gemm_inv_kernel(const T* A, const T* B, T* C, int M, int N, int K) {
  __shared__ float As[32][32];
  __shared__ float Bs[32][32];
  int row = blockIdx.y * 32 + threadIdx.y;
  int col = blockIdx.x * 32 + threadIdx.x;
  float acc = 0.0f;
  for (int k0 = 0; k0 < K; k0 += 32) {
    int ka = k0 + threadIdx.x, kb = k0 + threadIdx.y;
    As[threadIdx.y][threadIdx.x] =
        (row < M && ka < K) ? dev_to_f<T>(A[(size_t)row * K + ka]) : 0.0f;
    Bs[threadIdx.y][threadIdx.x] =
        (kb < K && col < N) ? dev_to_f<T>(B[(size_t)kb * N + col]) : 0.0f;
    __syncthreads();
    #pragma unroll
    for (int k = 0; k < 32; k++)
      acc = fmaf(As[threadIdx.y][k], Bs[k][threadIdx.x], acc);
    __syncthreads();
  }
  if (row < M && col < N) C[(size_t)row * N + col] = dev_from_f<T>(acc);
}

template <typename T>
static void launch_gemm_inv(const T* A, const T* B, T* C, int M, int N, int K, cudaStream_t st) {
  int mpad = ((M + 31) / 32) * 32;
  dim3 grid(N / 32, mpad / 32), block(32, 32);
  gemm_inv_kernel<T><<<grid, block, 0, st>>>(A, B, C, M, N, K);
}

// SiLU elementwise (fp16 storage, fp32 compute) — trivially batch-invariant.
__global__ void silu_kernel(const __half* x, __half* y, size_t n) {
  size_t i = (size_t)blockIdx.x * blockDim.x + threadIdx.x;
  if (i < n) {
    float v = __half2float(x[i]);
    y[i] = __float2half_rn(v / (1.0f + expf(-v)));
  }
}

// Repack [M, 3*H*D] QKV rows -> Q,K,V [B,H,S,D] and back (elementwise copies,
// deterministic). M = B*S.
__global__ void qkv_split_kernel(const __half* qkv, __half* Q, __half* K, __half* V,
                                 int B, int H, int S, int D) {
  size_t n = (size_t)B * H * S * D;
  size_t i = (size_t)blockIdx.x * blockDim.x + threadIdx.x;
  if (i >= n) return;
  int d = i % D; size_t t = i / D;
  int s = t % S; t /= S;
  int h = t % H; t /= H;
  int b = (int)t;
  size_t src = ((size_t)b * S + s) * (3 * H * D) + (size_t)h * D + d;
  Q[i] = qkv[src];
  K[i] = qkv[src + (size_t)H * D];
  V[i] = qkv[src + 2 * (size_t)H * D];
}
__global__ void o_merge_kernel(const __half* O, __half* out, int B, int H, int S, int D) {
  size_t n = (size_t)B * H * S * D;
  size_t i = (size_t)blockIdx.x * blockDim.x + threadIdx.x;
  if (i >= n) return;
  int d = i % D; size_t t = i / D;
  int s = t % S; t /= S;
  int h = t % H; t /= H;
  int b = (int)t;
  out[((size_t)b * S + s) * (H * D) + (size_t)h * D + d] = O[i];
}

// ---------------------------------------------------------------------------
// cuBLASLt GEMM (standard reference). Row-major C[M,N] = A[M,K] * B[K,N] via
// the column-major identity C^T = B^T A^T. FP16/BF16 use CUBLAS_COMPUTE_32F
// (SM120 tensor cores, fp32 accumulate); FP32 uses CUBLAS_COMPUTE_32F (plain
// fp32 CUDA cores; TF32 is NOT enabled). Heuristic top-1 algo, 32 MB workspace.
// Algo config (id, tile, stages, split-K, reduction scheme) is recorded as
// evidence of batch-dependent algorithm selection.
// ---------------------------------------------------------------------------
struct LtGemm {
  cublasLtHandle_t handle = nullptr;
  cublasLtMatmulDesc_t op = nullptr;
  cublasLtMatrixLayout_t la = nullptr, lb = nullptr, lc = nullptr;
  cublasLtMatmulPreference_t pref = nullptr;
  cublasLtMatmulAlgo_t algo;
  int algo_id = -1, tile = -1, stages = -1, splitk = -1, reduction = -1, swizzle = -1;
  size_t ws_size = 32 * 1024 * 1024;
  size_t ws_alloc = 32 * 1024 * 1024;
  void* ws = nullptr;
  int M = 0, N = 0, K = 0;
  DType dt = FP32;

  void init(DType dt_, int M_, int N_, int K_) {
    dt = dt_; M = M_; N = N_; K = K_;
    LT_CHECK(cublasLtCreate(&handle));
    LT_CHECK(cublasLtMatmulDescCreate(&op, CUBLAS_COMPUTE_32F, CUDA_R_32F));
    // Column-major views: A_lt = B (N x K), B_lt = A (K x M), C_lt = C (N x M).
    LT_CHECK(cublasLtMatrixLayoutCreate(&la, cuda_dtype(dt), N, K, N));
    LT_CHECK(cublasLtMatrixLayoutCreate(&lb, cuda_dtype(dt), K, M, K));
    LT_CHECK(cublasLtMatrixLayoutCreate(&lc, cuda_dtype(dt), N, M, N));
    LT_CHECK(cublasLtMatmulPreferenceCreate(&pref));
    LT_CHECK(cublasLtMatmulPreferenceSetAttribute(pref, CUBLASLT_MATMUL_PREF_MAX_WORKSPACE_BYTES,
                                                  &ws_size, sizeof(ws_size)));
    CUDA_CHECK(cudaMalloc(&ws, ws_size));
    cublasLtMatmulHeuristicResult_t res;
    int returned = 0;
    LT_CHECK(cublasLtMatmulAlgoGetHeuristic(handle, op, la, lb, lc, lc, pref, 1, &res, &returned));
    if (returned == 0) { fprintf(stderr, "no cuBLASLt algo for M=%d N=%d K=%d\n", M, N, K); exit(1); }
    algo = res.algo;
    if (res.workspaceSize > ws_alloc) {
      fprintf(stderr, "algo needs %zu workspace bytes > allocated %zu\n", res.workspaceSize, ws_alloc);
      exit(1);
    }
    ws_size = res.workspaceSize;
    auto get = [&](cublasLtMatmulAlgoConfigAttributes_t a) -> int {
      int v = -1; size_t w = 0;
      cublasStatus_t s = cublasLtMatmulAlgoConfigGetAttribute(&algo, a, &v, sizeof(v), &w);
      return (s == CUBLAS_STATUS_SUCCESS && w == sizeof(v)) ? v : -1;
    };
    algo_id = get(CUBLASLT_ALGO_CONFIG_ID);
    tile = get(CUBLASLT_ALGO_CONFIG_TILE_ID);
    stages = get(CUBLASLT_ALGO_CONFIG_STAGES_ID);
    splitk = get(CUBLASLT_ALGO_CONFIG_SPLITK_NUM);
    reduction = get(CUBLASLT_ALGO_CONFIG_REDUCTION_SCHEME);
    swizzle = get(CUBLASLT_ALGO_CONFIG_CTA_SWIZZLING);
  }
  void run(const void* A, const void* B, void* C, cudaStream_t st) {
    float alpha = 1.0f, beta = 0.0f;
    LT_CHECK(cublasLtMatmul(handle, op, &alpha, B, la, A, lb, &beta, C, lc, C, lc,
                            &algo, ws, ws_size, st));
  }
  void destroy() {
    if (ws) cudaFree(ws);
    if (pref) cublasLtMatmulPreferenceDestroy(pref);
    if (la) cublasLtMatrixLayoutDestroy(la);
    if (lb) cublasLtMatrixLayoutDestroy(lb);
    if (lc) cublasLtMatrixLayoutDestroy(lc);
    if (op) cublasLtMatmulDescDestroy(op);
    if (handle) cublasLtDestroy(handle);
    ws = nullptr; pref = nullptr; la = lb = lc = nullptr; op = nullptr; handle = nullptr;
  }
};

