// ---------------------------------------------------------------------------
// BLOCK — experiment 3b: end-to-end transformer-like block bitwise replay.
// RMSNorm -> QKV GEMM -> attention -> o GEMM -> RMSNorm -> FFN(up, SiLU, down).
// Probe = sequence 0 (S rows). Run with B=1 and B=7 (different surrounding
// batch padding / filler sequences), compare probe output bitwise.
// ---------------------------------------------------------------------------
struct BlockWeights {
  DevBuf wqkv, wo, wup, wdown, gn1, gn2;
  int H = 4096;
  void init(uint64_t seed) {
    Rng rng(seed);
    std::vector<char> h;
    fill_grid(h, (size_t)4096 * 12288, FP16, rng); wqkv.alloc(h.size()); wqkv.upload(h.data(), h.size());
    fill_grid(h, (size_t)4096 * 4096, FP16, rng); wo.alloc(h.size()); wo.upload(h.data(), h.size());
    fill_grid(h, (size_t)4096 * 11008, FP16, rng); wup.alloc(h.size()); wup.upload(h.data(), h.size());
    fill_grid(h, (size_t)11008 * 4096, FP16, rng); wdown.alloc(h.size()); wdown.upload(h.data(), h.size());
    std::vector<float> w1(4096), w2(4096);
    for (int i = 0; i < 4096; i++) w1[i] = rng.weight();
    for (int i = 0; i < 4096; i++) w2[i] = rng.weight();
    gn1.alloc(4096 * 4); gn1.upload(w1.data(), 4096 * 4);
    gn2.alloc(4096 * 4); gn2.upload(w2.data(), 4096 * 4);
  }
  void free_() { wqkv.free_(); wo.free_(); wup.free_(); wdown.free_(); gn1.free_(); gn2.free_(); }
};

// Run the block. invariant=true uses fixed-order kernels + invariant GEMM;
// false uses cuBLASLt + batch-heuristic kernels. Returns probe sequence output
// (S*4096 fp16) in host vector.
static void run_block(const BlockWeights& W, const std::vector<char>& hx_full,
                      int B, int S, bool invariant, std::vector<char>& out_probe) {
  const int HID = 4096, H = 32, D = 128, FFN = 11008;
  int M = B * S;
  DevBuf dx, dxn, dqkv, dQ, dK, dV, dO, dao, dxo, dxn2, dh, dh2, dy;
  dx.alloc((size_t)M * HID * 2); dx.upload(hx_full.data(), (size_t)M * HID * 2);
  dxn.alloc((size_t)M * HID * 2);
  dqkv.alloc((size_t)M * 3 * HID * 2);
  size_t nqkv = (size_t)B * H * S * D;
  dQ.alloc(nqkv * 2); dK.alloc(nqkv * 2); dV.alloc(nqkv * 2); dO.alloc(nqkv * 2);
  dao.alloc((size_t)M * HID * 2);
  dxo.alloc((size_t)M * HID * 2);
  dxn2.alloc((size_t)M * HID * 2);
  dh.alloc((size_t)M * FFN * 2);
  dh2.alloc((size_t)M * FFN * 2);
  dy.alloc((size_t)M * HID * 2);

  auto norm = [&](const DevBuf& in, const DevBuf& gn, DevBuf& outb) {
    int T = invariant ? ROW_BLOCK_INV : row_block_heuristic(B);
    rmsnorm_kernel<__half><<<M, T, (T / 32) * 4>>>((const __half*)in.p, (const float*)gn.p,
                                                   (__half*)outb.p, HID, 1e-5f);
  };
  auto gemm = [&](const DevBuf& A, const DevBuf& Bw, DevBuf& C, int K, int N) {
    if (invariant) {
      launch_gemm_inv<__half>((const __half*)A.p, (const __half*)Bw.p, (__half*)C.p, M, N, K, 0);
    } else {
      LtGemm g; g.init(FP16, M, N, K);
      g.run(A.p, Bw.p, C.p, 0);
      CUDA_CHECK(cudaDeviceSynchronize());
      g.destroy();
    }
  };
  size_t blk = 256;
  auto gridn = [&](size_t n) { return (unsigned)((n + blk - 1) / blk); };

  norm(dx, W.gn1, dxn);                                   // RMSNorm 1
  gemm(dxn, W.wqkv, dqkv, HID, 3 * HID);                  // QKV
  qkv_split_kernel<<<gridn(nqkv), blk>>>((const __half*)dqkv.p, (__half*)dQ.p, (__half*)dK.p,
                                         (__half*)dV.p, B, H, S, D);
  {
    int T = invariant ? ATTN_THREADS_INV : attn_threads_heuristic(B);
    attn_kernel<<<dim3(S, H, B), T, (S + T / 32) * 4>>>((const __half*)dQ.p, (const __half*)dK.p,
                                                        (const __half*)dV.p, (__half*)dO.p, H, S, D);
  }
  o_merge_kernel<<<gridn(nqkv), blk>>>((const __half*)dO.p, (__half*)dao.p, B, H, S, D);
  gemm(dao, W.wo, dxo, HID, HID);                         // o proj
  norm(dxo, W.gn2, dxn2);                                 // RMSNorm 2
  gemm(dxn2, W.wup, dh, HID, FFN);                        // FFN up
  silu_kernel<<<gridn((size_t)M * FFN), blk>>>((const __half*)dh.p, (__half*)dh2.p, (size_t)M * FFN);
  gemm(dh2, W.wdown, dy, FFN, HID);                       // FFN down
  CUDA_CHECK(cudaDeviceSynchronize());
  out_probe.resize((size_t)S * HID * 2);
  dy.download(out_probe.data(), out_probe.size());
  dx.free_(); dxn.free_(); dqkv.free_(); dQ.free_(); dK.free_(); dV.free_(); dO.free_();
  dao.free_(); dxo.free_(); dxn2.free_(); dh.free_(); dh2.free_(); dy.free_();
}

static void mode_block() {
  printf("{\"mode\":\"block_header\","); print_device_info(); printf("\"seq\":128}\n");
  const int S = 128, HID = 4096;
  uint64_t seed = SEEDS[0];
  BlockWeights W; W.init(seed);
  // input cohort: max B=7 sequences; probe = sequence 0, identical in both runs
  Rng rng(seed + 1);
  std::vector<char> hx; fill_grid(hx, (size_t)7 * S * HID, FP16, rng);
  std::vector<char> y1, y7, y1rep, s1, s7;
  run_block(W, hx, 1, S, true, y1);
  run_block(W, hx, 7, S, true, y7);
  run_block(W, hx, 1, S, true, y1rep);
  run_block(W, hx, 1, S, false, s1);
  run_block(W, hx, 7, S, false, s7);
  CmpResult inv = cmp_rows(y1.data(), y7.data(), (size_t)S * HID, FP16);
  CmpResult invrep = cmp_rows(y1.data(), y1rep.data(), (size_t)S * HID, FP16);
  CmpResult std_ = cmp_rows(s1.data(), s7.data(), (size_t)S * HID, FP16);
  printf("{\"kernel\":\"block_replay\",\"seq\":%d,\"hidden\":%d,\"B_a\":1,\"B_b\":7,"
         "\"elements_compared\":%zu,\"seed\":%llu,", S, HID, (size_t)S * HID,
         (unsigned long long)seed);
  printf("\"invariant_bitwise_equal\":%s,", inv.identical() ? "true" : "false");
  cmp_json(inv);
  printf(",\"invariant_repeat_equal\":%s,\"standard_bitwise_equal\":%s,"
         "\"standard_diff_count\":%zu,\"standard_diff_fraction\":%.9g,\"standard_max_ulp\":%lld}\n",
         invrep.identical() ? "true" : "false", std_.identical() ? "true" : "false",
         std_.diff, (double)std_.diff / ((double)S * HID), (long long)std_.max_ulp);
  W.free_();
  printf("{\"mode\":\"block_footer\"}\n");
}

