// bik.cu — Batch-invariant deterministic inference kernels on SM120 (Blackwell).
//
// Study: batch-size-induced bitwise nondeterminism in standard GPU inference
// kernels (cuBLASLt GEMM FP16/BF16/FP32, row softmax, RMSNorm, naive tiled
// attention) and the cost of fixed-reduction-order batch-invariant variants.
//
// ALL GPU work targets compute capability 12.0 (RTX 5060 Ti). Compile with
// -arch=sm_120. Run with CUDA_VISIBLE_DEVICES=0.
//
// Modes (each prints one JSON object to stdout):
//   selftest   — comparator / bound-checker negative controls
//   measure    — experiment 1: bitwise probe-row differences across batch sizes
//   invariant  — experiment 2: acceptance test (bitwise invariance) + exact
//                fp64 CPU oracle for the FP32 GEMM probe row + tolerances
//   cost       — experiment 3a: resident median latency, invariant vs standard
//   block      — experiment 3b: end-to-end transformer-like block bitwise replay
//
// Data contract: every input element is a multiple of 2^-8 in [-2, 2]
// (integers k in [-512, 512] divided by 256), generated by splitmix64.
// For FP16 these values are exactly representable; for BF16 they are rounded
// to BF16 first. This makes the fp64 sequential CPU oracle EXACT (proven
// bound in METHODS.md: K * 4 * 2^36 < 2^53 for K <= 11008).
//
// Probe-row protocol: row 0 is the fixed probe. A batch of size M uses the
// first M rows of one max-batch cohort (same seed), so smaller batches are
// prefixes of larger ones: the probe row and all filler rows are identical
// across batch sizes and only the batch size changes.

