struct GemmShape { int K, N; const char* name; };
static const GemmShape GEMM_SHAPES[3] = {
    {4096, 4096, "hidden_square"}, {4096, 11008, "ffn_up"}, {11008, 4096, "ffn_down"}};

static void measure_gemm() {
  for (int dti = 0; dti < 3; dti++) {
    DType dt = (DType)dti;
    for (int si = 0; si < 3; si++) {
      int K = GEMM_SHAPES[si].K, N = GEMM_SHAPES[si].N;
      for (int seedi = 0; seedi < 2; seedi++) {
        uint64_t seed = SEEDS[seedi];
        Rng rng(seed);
        std::vector<char> hA, hB;
        fill_grid(hA, (size_t)MAXB * K, dt, rng);
        fill_grid(hB, (size_t)K * N, dt, rng);
        DevBuf dA, dB, dC;
        dA.alloc(hA.size()); dA.upload(hA.data(), hA.size());
        dB.alloc(hB.size()); dB.upload(hB.data(), hB.size());
        dC.alloc((size_t)MAXB * N * dtype_size(dt));
        std::vector<char> ref(N * dtype_size(dt)), cur(N * dtype_size(dt)), rep(N * dtype_size(dt));
        bool have_ref = false;
        for (int bi = 0; bi < 5; bi++) {
          int M = BATCHES[bi];
          LtGemm g; g.init(dt, M, N, K);
          g.run(dA.p, dB.p, dC.p, 0);
          CUDA_CHECK(cudaDeviceSynchronize());
          dC.download(cur.data(), (size_t)N * dtype_size(dt));
          // run-to-run repeat at the same batch size
          g.run(dA.p, dB.p, dC.p, 0);
          CUDA_CHECK(cudaDeviceSynchronize());
          dC.download(rep.data(), (size_t)N * dtype_size(dt));
          CmpResult rr = cmp_rows(cur.data(), rep.data(), N, dt);
          if (!have_ref) { memcpy(ref.data(), cur.data(), ref.size()); have_ref = true; }
          CmpResult c = cmp_rows(ref.data(), cur.data(), N, dt);
          printf("{\"kernel\":\"gemm_cublaslt\",\"dtype\":\"%s\",\"shape\":\"%s\",\"K\":%d,\"N\":%d,"
                 "\"M\":%d,\"seed\":%llu,\"algo_id\":%d,\"tile_id\":%d,\"stages_id\":%d,"
                 "\"splitk\":%d,\"reduction_scheme\":%d,\"cta_swizzle\":%d,",
                 dtype_name(dt), GEMM_SHAPES[si].name, K, N, M, (unsigned long long)seed,
                 g.algo_id, g.tile, g.stages, g.splitk, g.reduction, g.swizzle);
          cmp_json(c);
          printf(",\"repeat_run_diff_count\":%zu,\"repeat_run_max_ulp\":%lld}\n",
                 rr.diff, (long long)rr.max_ulp);
          g.destroy();
        }
        dA.free_(); dB.free_(); dC.free_();
      }
    }
  }
}

