// ---------------------------------------------------------------------------
// SELFTEST — negative controls for the verification machinery itself.
// ---------------------------------------------------------------------------
static void mode_selftest() {
  printf("{"); print_device_info();
  // 1. Comparator must detect a single-bit flip (deliberately wrong output).
  float a[64], b[64];
  Rng rng(42);
  for (int i = 0; i < 64; i++) { a[i] = rng.grid(); b[i] = a[i]; }
  uint32_t bits; memcpy(&bits, &b[17], 4); bits ^= 1u; memcpy(&b[17], &bits, 4);
  CmpResult r = cmp_rows((const char*)a, (const char*)b, 64, FP32);
  bool flip_detected = (r.diff == 1 && r.max_ulp == 1);
  // 2. Identical buffers must compare identical.
  CmpResult r0 = cmp_rows((const char*)a, (const char*)a, 64, FP32);
  // 3. fp16 comparator flip check.
  uint16_t h1[8], h2[8];
  for (int i = 0; i < 8; i++) { h1[i] = f32_to_f16_bits(a[i]); h2[i] = h1[i]; }
  h2[3] ^= 1u;
  CmpResult rh = cmp_rows((const char*)h1, (const char*)h2, 8, FP16);
  // 4. Bound checker: a value perturbed beyond the proven bound must be rejected.
  double exact = 1.25, bound = 1e-3;
  auto within = [&](double gpu) { return fabs(gpu - exact) <= bound; };
  bool ok_in = within(exact + bound * 0.5);
  bool reject_out = !within(exact + bound * 1.01);
  // 5. RNG determinism: same seed -> same stream.
  Rng r1(20261119), r2(20261119);
  bool rng_det = true;
  for (int i = 0; i < 1000; i++) if (r1.next() != r2.next()) rng_det = false;
  printf("\"selftest\":{\"single_bit_flip_detected\":%s,\"flip_ulp\":%lld,"
         "\"identical_buffers_pass\":%s,\"fp16_flip_detected\":%s,"
         "\"bound_checker_accepts_inside\":%s,\"bound_checker_rejects_outside\":%s,"
         "\"rng_deterministic\":%s,\"pass\":%s}}\n",
         flip_detected ? "true" : "false", (long long)r.max_ulp,
         r0.identical() ? "true" : "false",
         (rh.diff == 1 && rh.max_ulp == 1) ? "true" : "false",
         ok_in ? "true" : "false", reject_out ? "true" : "false",
         rng_det ? "true" : "false",
         (flip_detected && r0.identical() && rh.diff == 1 && ok_in && reject_out && rng_det)
             ? "true" : "false");
}

