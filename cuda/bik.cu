enum DType { FP16, BF16, FP32 };
static const char* dtype_name(DType t) { return t == FP16 ? "fp16" : t == BF16 ? "bf16" : "fp32"; }
static cudaDataType_t cuda_dtype(DType t) {
  return t == FP16 ? CUDA_R_16F : t == BF16 ? CUDA_R_16BF : CUDA_R_32F;
}
static size_t dtype_size(DType t) { return t == FP32 ? 4 : 2; }

static float to_float_f(__half h) { return __half2float(h); }
static float to_float_f(__nv_bfloat16 b) { return __bfloat162float(b); }
static float to_float_f(float f) { return f; }

// Host conversions (round-to-nearest-even, same as device).
static uint16_t f32_to_f16_bits(float f) { __half h = __float2half_rn(f); uint16_t u; memcpy(&u, &h, 2); return u; }
static uint16_t f32_to_bf16_bits(float f) { __nv_bfloat16 b = __float2bfloat16_rn(f); uint16_t u; memcpy(&u, &b, 2); return u; }
static float f16_bits_to_f32(uint16_t u) { __half h; memcpy(&h, &u, 2); return __half2float(h); }
static float bf16_bits_to_f32(uint16_t u) { __nv_bfloat16 b; memcpy(&b, &u, 2); return __bfloat162float(b); }

// Fill a host buffer with grid values in the target dtype.
static void fill_grid(std::vector<char>& buf, size_t n, DType t, Rng& rng) {
  buf.resize(n * dtype_size(t));
  if (t == FP32) {
    float* p = (float*)buf.data();
    for (size_t i = 0; i < n; i++) p[i] = rng.grid();
  } else if (t == FP16) {
    uint16_t* p = (uint16_t*)buf.data();
    for (size_t i = 0; i < n; i++) p[i] = f32_to_f16_bits(rng.grid());
  } else {
    uint16_t* p = (uint16_t*)buf.data();
    for (size_t i = 0; i < n; i++) p[i] = f32_to_bf16_bits(rng.grid());
  }
}

// Decode one element to float (for the CPU oracle).
static float elem_to_f32(const char* buf, size_t i, DType t) {
  if (t == FP32) return ((const float*)buf)[i];
  uint16_t u = ((const uint16_t*)buf)[i];
  return t == FP16 ? f16_bits_to_f32(u) : bf16_bits_to_f32(u);
}

// ---------------------------------------------------------------------------
// Bitwise comparison + ULP distance (ordered-integer mapping of IEEE bits).
// ---------------------------------------------------------------------------
static int64_t ordered32(uint32_t b) {
  // IEEE bits -> monotone ordered integer: negatives map to [0, 2^31),
  // positives to [2^31, 2^32). Adjacent representable values differ by 1.
  return (b & 0x80000000u) ? (int64_t)(~b) : (int64_t)(b | 0x80000000u);
}
static int64_t ordered16(uint16_t b) {
  return (b & 0x8000u) ? (int64_t)((uint16_t)~b) : (int64_t)(b | 0x8000u);
}

struct CmpResult {
  size_t n = 0, diff = 0;
  int64_t max_ulp = 0;
  double max_abs = 0.0;
  bool identical() const { return diff == 0; }
};

// Compare two probe rows bitwise; ULP distance in the storage dtype.
static CmpResult cmp_rows(const char* a, const char* b, size_t n, DType t) {
  CmpResult r; r.n = n;
  size_t es = dtype_size(t);
  for (size_t i = 0; i < n; i++) {
    if (memcmp(a + i * es, b + i * es, es) != 0) {
      r.diff++;
      int64_t ulp;
      double fa, fb;
      if (t == FP32) {
        uint32_t ua, ub; memcpy(&ua, a + i * 4, 4); memcpy(&ub, b + i * 4, 4);
        ulp = llabs(ordered32(ua) - ordered32(ub));
        fa = ((const float*)a)[i]; fb = ((const float*)b)[i];
      } else {
        uint16_t ua, ub; memcpy(&ua, a + i * 2, 2); memcpy(&ub, b + i * 2, 2);
        ulp = llabs(ordered16(ua) - ordered16(ub));
        fa = elem_to_f32(a, i, t); fb = elem_to_f32(b, i, t);
      }
      if (ulp > r.max_ulp) r.max_ulp = ulp;
      double d = fabs(fa - fb);
      if (d > r.max_abs) r.max_abs = d;
    }
  }
  return r;
}

// ---------------------------------------------------------------------------
// Device helpers: dtype conversion, block reductions (order depends on
// blockDim.x — this is the batch-dependent mechanism for row-wise kernels).
// ---------------------------------------------------------------------------
template <typename T> __device__ __forceinline__ float dev_to_f(T v);
template <> __device__ __forceinline__ float dev_to_f<__half>(__half v) { return __half2float(v); }
template <> __device__ __forceinline__ float dev_to_f<__nv_bfloat16>(__nv_bfloat16 v) { return __bfloat162float(v); }
template <> __device__ __forceinline__ float dev_to_f<float>(float v) { return v; }

template <typename T> __device__ __forceinline__ T dev_from_f(float v);
template <> __device__ __forceinline__ __half dev_from_f<__half>(float v) { return __float2half_rn(v); }
template <> __device__ __forceinline__ __nv_bfloat16 dev_from_f<__nv_bfloat16>(float v) { return __float2bfloat16_rn(v); }
template <> __device__ __forceinline__ float dev_from_f<float>(float v) { return v; }

// Warp-level sum, fixed shuffle-down tree (lanes 16,8,4,2,1).
__device__ __forceinline__ float warp_sum(float v) {
  #pragma unroll
  for (int o = 16; o > 0; o >>= 1) v += __shfl_down_sync(0xffffffffu, v, o);
  return v;
}
__device__ __forceinline__ float warp_max(float v) {
  #pragma unroll
  for (int o = 16; o > 0; o >>= 1) v = fmaxf(v, __shfl_down_sync(0xffffffffu, v, o));
  return v;
}

// Block sum: per-warp shuffle tree, then first warp reduces warp partials in
// lane order. Total order depends on blockDim.x (number of warps/lanes).
// smem must hold blockDim.x/32 floats.
__device__ __forceinline__ float block_sum(float v, float* smem) {
  int lane = threadIdx.x & 31, wid = threadIdx.x >> 5;
  int nw = (blockDim.x + 31) >> 5;
  v = warp_sum(v);
  if (lane == 0) smem[wid] = v;
  __syncthreads();
  if (wid == 0) {
    v = (lane < nw) ? smem[lane] : 0.0f;
    v = warp_sum(v);
    if (lane == 0) smem[0] = v;
  }
  __syncthreads();
  float r = smem[0];
  __syncthreads();  // all reads complete before smem is reused
  return r;
}
__device__ __forceinline__ float block_max(float v, float* smem) {
  int lane = threadIdx.x & 31, wid = threadIdx.x >> 5;
  int nw = (blockDim.x + 31) >> 5;
  v = warp_max(v);
  if (lane == 0) smem[wid] = v;
  __syncthreads();
  if (wid == 0) {
    v = (lane < nw) ? smem[lane] : -INFINITY;
    v = warp_max(v);
    if (lane == 0) smem[0] = v;
  }
  __syncthreads();
  float r = smem[0];
  __syncthreads();
  return r;
}

// ---------------------------------------------------------------------------
// Row softmax: two-pass (max, then sum of exp), one block per row.
// "Standard" launch heuristic picks blockDim from the batch size; the
// invariant variant freezes blockDim = 256. Kernel body is identical.
// ---------------------------------------------------------------------------
template <typename T>
__global__ void softmax_kernel(const T* x, T* y, int N) {
  extern __shared__ float sm[];
  const T* xr = x + (size_t)blockIdx.x * N;
  T* yr = y + (size_t)blockIdx.x * N;
  float m = -INFINITY;
  for (int i = threadIdx.x; i < N; i += blockDim.x) m = fmaxf(m, dev_to_f<T>(xr[i]));
  m = block_max(m, sm);
  float s = 0.0f;
  for (int i = threadIdx.x; i < N; i += blockDim.x) s += expf(dev_to_f<T>(xr[i]) - m);
  s = block_sum(s, sm);
  float inv = 1.0f / s;
  for (int i = threadIdx.x; i < N; i += blockDim.x)
    yr[i] = dev_from_f<T>(expf(dev_to_f<T>(xr[i]) - m) * inv);
}

// RMSNorm: y = x * rsqrt(mean(x^2) + eps) * w. Same reduction structure.
template <typename T>
__global__ void rmsnorm_kernel(const T* x, const float* w, T* y, int N, float eps) {
  extern __shared__ float sm[];
  const T* xr = x + (size_t)blockIdx.x * N;
  T* yr = y + (size_t)blockIdx.x * N;
  float ss = 0.0f;
  for (int i = threadIdx.x; i < N; i += blockDim.x) {
    float v = dev_to_f<T>(xr[i]);
    ss += v * v;
  }
  ss = block_sum(ss, sm);
  float r = rsqrtf(ss / (float)N + eps);
  for (int i = threadIdx.x; i < N; i += blockDim.x)
    yr[i] = dev_from_f<T>(dev_to_f<T>(xr[i]) * r * w[i]);
}

