        attn_kernel<<<grid, ATTN_THREADS_INV, smem>>>((const __half*)dQ.p, (const __half*)dK.p,
                                                      (const __half*)dV.p, (__half*)dO.p, H, S, D);
        CUDA_CHECK(cudaDeviceSynchronize());
        dO.download(cur.data(), D * 2);
        if (!have_ref) {
          memcpy(ref.data(), cur.data(), ref.size()); have_ref = true;
          int T = attn_threads_heuristic(1);
          attn_kernel<<<dim3(S, H, 1), T, (S + T / 32) * 4>>>(
              (const __half*)dQ.p, (const __half*)dK.p, (const __half*)dV.p, (__half*)dO.p, H, S, D);
          CUDA_CHECK(cudaDeviceSynchronize());
          dO.download(stdref.data(), D * 2);
          CmpResult cs = cmp_rows(stdref.data(), ref.data(), D, FP16);
          max_ulp_std = cs.max_ulp; max_abs_std = cs.max_abs;
        }
        CmpResult c = cmp_rows(ref.data(), cur.data(), D, FP16);
        if (!c.identical()) pass = false;
        total_diff += c.diff;
      }
      printf("{\"kernel\":\"attn_invariant\",\"S\":%d,\"H\":%d,\"D\":%d,\"seed\":%llu,"
             "\"threads\":%d,\"acceptance_pass\":%s,\"total_diff_elements\":%zu,"
             "\"max_ulp_vs_std_b1\":%lld,\"max_abs_vs_std_b1\":%.9g}\n",
             S, H, D, (unsigned long long)seed, ATTN_THREADS_INV,
             pass ? "true" : "false", total_diff, (long long)max_ulp_std, max_abs_std);
      dQ.free_(); dK.free_(); dV.free_(); dO.free_();
    }
  }
}

// Negative controls: run the STANDARD (batch-dependent) kernels through the
// same acceptance harness. Two flavors:
//  - "targeted": cases where experiment 1 OBSERVED batch dependence (fp16
//    ffn_up GEMM, softmax width 11008). The harness MUST flag these — proving
//    it detects nondeterminism rather than trivially passing everything.
//  - "zero_diff_case": cases where experiment 1 observed NO difference (fp16
//    hidden_square GEMM, softmax width 4096). The harness must correctly pass
//    these — a zero-difference finding is valid and must not be forced false.
static void nc_std_gemm(DType dt, int K, int N, uint64_t seed, const char* case_tag) {
  Rng rng(seed);
  std::vector<char> hA, hB;
  fill_grid(hA, (size_t)MAXB * K, dt, rng);
  fill_grid(hB, (size_t)K * N, dt, rng);
  DevBuf dA, dB, dC;
  dA.alloc(hA.size()); dA.upload(hA.data(), hA.size());
  dB.alloc(hB.size()); dB.upload(hB.data(), hB.size());
  dC.alloc((size_t)MAXB * N * dtype_size(dt));
  std::vector<char> ref(N * dtype_size(dt)), cur(N * dtype_size(dt));
  bool have_ref = false, any_diff = false; size_t total_diff = 0;
  for (int bi = 0; bi < 5; bi++) {
    LtGemm g; g.init(dt, BATCHES[bi], N, K);
    g.run(dA.p, dB.p, dC.p, 0);
    CUDA_CHECK(cudaDeviceSynchronize());
    dC.download(cur.data(), (size_t)N * dtype_size(dt));
    if (!have_ref) { memcpy(ref.data(), cur.data(), ref.size()); have_ref = true; }
    CmpResult c = cmp_rows(ref.data(), cur.data(), N, dt);
    if (!c.identical()) any_diff = true;
    total_diff += c.diff;
    g.destroy();
  }
  printf("{\"kernel\":\"negative_control_std_gemm\",\"case\":\"%s\",\"dtype\":\"%s\","
         "\"K\":%d,\"N\":%d,\"seed\":%llu,\"std_fails_acceptance\":%s,"
         "\"total_diff_elements\":%zu}\n",
         case_tag, dtype_name(dt), K, N, (unsigned long long)seed,
         any_diff ? "true" : "false", total_diff);
  dA.free_(); dB.free_(); dC.free_();
}

static void nc_std_softmax(int N, uint64_t seed, const char* case_tag) {
  Rng rng(seed);
  std::vector<char> hx; fill_grid(hx, (size_t)MAXB * N, FP32, rng);
  DevBuf dx, dy;
  dx.alloc(hx.size()); dx.upload(hx.data(), hx.size());
  dy.alloc((size_t)MAXB * N * 4);
  std::vector<char> ref(N * 4), cur(N * 4);
  bool have_ref = false, any_diff = false; size_t total_diff = 0;
  for (int bi = 0; bi < 5; bi++) {
    int B = BATCHES[bi], T = row_block_heuristic(B);
    softmax_kernel<float><<<B, T, (T / 32) * 4>>>((const float*)dx.p, (float*)dy.p, N);
    CUDA_CHECK(cudaDeviceSynchronize());
    dy.download(cur.data(), N * 4);
    if (!have_ref) { memcpy(ref.data(), cur.data(), ref.size()); have_ref = true; }
    CmpResult c = cmp_rows(ref.data(), cur.data(), N, FP32);
    if (!c.identical()) any_diff = true;
    total_diff += c.diff;
  }
  printf("{\"kernel\":\"negative_control_std_softmax\",\"case\":\"%s\",\"N\":%d,"
         "\"seed\":%llu,\"std_fails_acceptance\":%s,\"total_diff_elements\":%zu}\n",
         case_tag, N, (unsigned long long)seed, any_diff ? "true" : "false", total_diff);
  dx.free_(); dy.free_();
}

static void negative_control_std() {
  nc_std_gemm(FP16, 4096, 11008, SEEDS[0], "targeted");       // observed: split-K switch
  nc_std_softmax(11008, SEEDS[0], "targeted");                // observed: <=2 ULP fp32
  nc_std_gemm(FP16, 4096, 4096, SEEDS[0], "zero_diff_case");  // observed: no difference
  nc_std_softmax(4096, SEEDS[0], "zero_diff_case");           // observed: no difference
}

