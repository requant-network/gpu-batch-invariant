// ---------------------------------------------------------------------------
// Host RNG: splitmix64 (identical implementation re-used by the independent
// Python oracle in tests/validate_results.py).
// ---------------------------------------------------------------------------
struct Rng {
  uint64_t s;
  explicit Rng(uint64_t seed) : s(seed) {}
  uint64_t next() {
    s += 0x9E3779B97F4A7C15ULL;
    uint64_t z = s;
    z = (z ^ (z >> 30)) * 0xBF58476D1CE4E5B9ULL;
    z = (z ^ (z >> 27)) * 0x94D049BB133111EBULL;
    return z ^ (z >> 31);
  }
  // grid value: multiple of 2^-8 in [-2, 2]
  float grid() { return (float)((int64_t)(next() % 1025) - 512) / 256.0f; }
  // weight near 1: 1 + k/1024, k in [-128, 128)
  float weight() { return 1.0f + (float)((int64_t)(next() % 256) - 128) / 1024.0f; }
};

